function warnUnmappedKeys(names) {
  const unmapped = names.filter((name) => !KEYMAP[name]?.length || KEYMAP[name].includes(undefined));
  if (unmapped.length) log.warn('input', `No key mapping for: ${unmapped.join(', ')}`);
}

